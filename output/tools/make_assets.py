#!/usr/bin/env python3
"""Generates the small ZIP test assets used to verify miniz's LZMA reader support.

Assets (all tiny, written to output/assets/):
  content.bin        - reference uncompressed payload
  lzma.zip           - test.bin (LZMA, method 14) + note.txt (stored)
  deflate.zip        - same payload, deflate (regression reference)
  lzma_badcrc.zip    - LZMA zip with corrupted stored CRC-32
  lzma_corrupt.zip   - LZMA zip with a corrupted compressed-data byte
  lzma_badprops.zip  - LZMA zip with unsupported properties size (subtype)
  bzip2.zip          - test.bin compressed with bzip2 (method 12, unsupported)

Also emits tests/lzma_test_data.h with the fixtures embedded as C arrays
for the catch2 reader tests.
"""
import os
import struct
import zipfile

HERE = os.path.dirname(os.path.abspath(__file__))
ASSETS = os.path.normpath(os.path.join(HERE, "..", "assets"))
REPO = os.path.normpath(os.path.join(HERE, "..", ".."))

# Small but not trivial payload: compressible text with a less regular tail.
CONTENT = (
    b"The quick brown fox jumps over the lazy dog. " * 40
    + bytes((i * 37 + 11) % 251 for i in range(120))
)
NOTE = b"created by make_assets.py\n"


def make_zip(path, content, compression, note=True):
    with zipfile.ZipFile(path, "w") as z:
        info = zipfile.ZipInfo("test.bin", date_time=(2020, 1, 2, 3, 4, 5))
        info.compress_type = compression
        info.comment = b"test Comment"
        info.external_attr = 0o644 << 16
        z.writestr(info, content)
        if note:
            z.writestr("note.txt", NOTE, compress_type=zipfile.ZIP_STORED)
    with open(path, "rb") as f:
        return bytearray(f.read())


def patch_crc(data):
    """Corrupt the CRC-32 fields in the local and central directory headers of test.bin."""
    data = bytearray(data)
    # local header: signature PK\x03\x04, CRC at offset 14
    assert data[:4] == b"PK\x03\x04"
    data[14] ^= 0xFF
    # locate the central directory via the end of central directory record
    eocd = data.rfind(b"PK\x05\x06")
    assert eocd > 0
    cd = struct.unpack("<I", data[eocd + 16 : eocd + 20])[0]
    assert data[cd : cd + 4] == b"PK\x01\x02"
    # central directory: signature PK\x01\x02, CRC at offset 16
    data[cd + 16] ^= 0xFF
    return data


def find_comp_data(data):
    """Return (offset, size) of the first entry's compressed data."""
    assert data[:4] == b"PK\x03\x04"
    nlen, elen = struct.unpack("<HH", data[26:30])
    csize = struct.unpack("<I", data[18:22])[0]
    return 30 + nlen + elen, csize


def patch_corrupt(data):
    """Flip one byte near the end of the LZMA payload."""
    data = bytearray(data)
    ofs, csize = find_comp_data(data)
    data[ofs + csize - 2] ^= 0xFF
    return data


def patch_badprops(data):
    """Change the ZIP LZMA properties size from 5 to 4 (unsupported subtype)."""
    data = bytearray(data)
    ofs, csize = find_comp_data(data)
    assert data[ofs + 2] == 5 and data[ofs + 3] == 0
    data[ofs + 2] = 4
    return data


def c_array(name, data):
    lines = ["static const unsigned char %s[] = {" % name]
    for i in range(0, len(data), 12):
        lines.append("    " + ", ".join("0x%02x" % b for b in data[i : i + 12]) + ",")
    lines.append("};")
    return "\n".join(lines)
    lines.append("};")
    return "\n".join(lines)


def main():
    os.makedirs(ASSETS, exist_ok=True)

    with open(os.path.join(ASSETS, "content.bin"), "wb") as f:
        f.write(CONTENT)

    lzma_zip = make_zip(os.path.join(ASSETS, "lzma.zip"), CONTENT, zipfile.ZIP_LZMA)
    make_zip(os.path.join(ASSETS, "deflate.zip"), CONTENT, zipfile.ZIP_DEFLATED)

    variants = {
        "lzma_badcrc": patch_crc(lzma_zip),
        "lzma_corrupt": patch_corrupt(lzma_zip),
        "lzma_badprops": patch_badprops(lzma_zip),
    }
    for name, data in variants.items():
        with open(os.path.join(ASSETS, name + ".zip"), "wb") as f:
            f.write(data)

    bzip2_zip = make_zip(os.path.join(ASSETS, "bzip2.zip"), CONTENT, zipfile.ZIP_BZIP2)

    # Sanity: reference implementation must extract the good LZMA zip byte-identically.
    with zipfile.ZipFile(os.path.join(ASSETS, "lzma.zip")) as z:
        assert z.read("test.bin") == CONTENT

    header = [
        "/* Auto-generated by output/tools/make_assets.py - small ZIP/LZMA reader fixtures. */",
        "#pragma once",
        "",
        c_array("k_lzma_zip", lzma_zip),
        "",
        c_array("k_lzma_zip_badcrc", variants["lzma_badcrc"]),
        "",
        c_array("k_lzma_zip_corrupt", variants["lzma_corrupt"]),
        "",
        c_array("k_lzma_zip_badprops", variants["lzma_badprops"]),
        "",
        c_array("k_bzip2_zip", bzip2_zip),
        "",
        c_array("k_lzma_content", CONTENT),
        "",
    ]
    out = os.path.join(REPO, "tests", "lzma_test_data.h")
    with open(out, "w") as f:
        f.write("\n".join(header))

    for name in sorted(os.listdir(ASSETS)):
        print("%s: %d bytes" % (name, os.path.getsize(os.path.join(ASSETS, name))))
    print("wrote", out)


if __name__ == "__main__":
    main()
